for (const [code, dict] of Object.entries(globalLocales)) {
  const filePath = path.join(localesDir, `${code}.ts`);
  if (!fs.existsSync(filePath)) continue;
  let content = fs.readFileSync(filePath, 'utf-8');
  let missingEntries = [];
  for (const [k, v] of Object.entries(dict)) {
    if (!content.includes(`${k}:`) && !content.includes(`'${k}':`) && !content.includes(`"${k}":`)) {
      const keyStr = k.includes('.') ? `'${k}'` : k;
      missingEntries.push(`  ${keyStr}: ${JSON.stringify(v)},`);
    }
  }
  if (missingEntries.length > 0) {
    content = content.replace(/\n\};\s*$/, '\n' + missingEntries.join('\n') + '\n};\n');
    fs.writeFileSync(filePath, content, 'utf-8');
    console.log(`Updated ${code}.ts with ${missingEntries.length} keys`);
  }
}

// Resolver function: Get authentic regional soil profile for active farm location
export function resolveRegionalSoilProfile(
  stateName?: string,
  districtName?: string,
  country = 'India'
): RegionalSoilProfile {
  const isIndia = !country || country.toLowerCase() === 'india';

  if (isIndia) {
    const cleanState = (stateName || '').trim();
    const cleanDist = (districtName || '').trim();
    const registryKeys = Object.keys(INDIA_REGIONAL_SOIL_REGISTRY);

    // 1. Try matching stateName first
    let matchedKey: string | undefined;

    if (cleanState) {
      matchedKey =
        registryKeys.find((k) => k.toLowerCase() === cleanState.toLowerCase()) ||
        registryKeys.find(
          (k) =>
            cleanState.toLowerCase().includes(k.toLowerCase()) ||
            k.toLowerCase().includes(cleanState.toLowerCase())
        );
    }

    // 2. If stateName did not match, check if districtName or cleanDist contains a known state or recognized district
    if (!matchedKey && cleanDist) {
      // Check if cleanDist is actually "Adilabad, Telangana" or contains a state name
      matchedKey = registryKeys.find((k) => cleanDist.toLowerCase().includes(k.toLowerCase()));

      // Check common district associations
      if (!matchedKey) {
        const lowerDist = cleanDist.toLowerCase();
        if (lowerDist.includes('adilabad') || lowerDist.includes('warangal') || lowerDist.includes('karimnagar') || lowerDist.includes('hyderabad') || lowerDist.includes('khammam') || lowerDist.includes('nizamabad') || lowerDist.includes('nalgonda') || lowerDist.includes('mahabubnagar')) {
          matchedKey = 'Telangana';
        } else if (lowerDist.includes('ludhiana') || lowerDist.includes('amritsar') || lowerDist.includes('patiala') || lowerDist.includes('jalandhar') || lowerDist.includes('bathinda') || lowerDist.includes('sangrur')) {
          matchedKey = 'Punjab';
        } else if (lowerDist.includes('nashik') || lowerDist.includes('pune') || lowerDist.includes('akola') || lowerDist.includes('nagpur') || lowerDist.includes('solapur') || lowerDist.includes('aurangabad') || lowerDist.includes('amravati')) {
          matchedKey = 'Maharashtra';
        } else if (lowerDist.includes('kolar') || lowerDist.includes('dharwad') || lowerDist.includes('belagavi') || lowerDist.includes('mandya') || lowerDist.includes('mysuru') || lowerDist.includes('bengaluru')) {
          matchedKey = 'Karnataka';
        } else if (lowerDist.includes('coimbatore') || lowerDist.includes('madurai') || lowerDist.includes('thanjavur') || lowerDist.includes('salem') || lowerDist.includes('tiruchirappalli')) {
          matchedKey = 'Tamil Nadu';
        } else if (lowerDist.includes('guntur') || lowerDist.includes('kurnool') || lowerDist.includes('krishna') || lowerDist.includes('anantapur') || lowerDist.includes('visakhapatnam')) {
          matchedKey = 'Andhra Pradesh';
        } else if (lowerDist.includes('varanasi') || lowerDist.includes('meerut') || lowerDist.includes('lucknow') || lowerDist.includes('kanpur') || lowerDist.includes('agra') || lowerDist.includes('prayagraj')) {
          matchedKey = 'Uttar Pradesh';
        } else if (lowerDist.includes('indore') || lowerDist.includes('bhopal') || lowerDist.includes('ujjain') || lowerDist.includes('jabalpur') || lowerDist.includes('hoshangabad') || lowerDist.includes('sehore')) {
          matchedKey = 'Madhya Pradesh';
        } else if (lowerDist.includes('rajkot') || lowerDist.includes('anand') || lowerDist.includes('junagadh') || lowerDist.includes('mehsana') || lowerDist.includes('surat') || lowerDist.includes('vadodara')) {
          matchedKey = 'Gujarat';
        } else if (lowerDist.includes('karnal') || lowerDist.includes('hisar') || lowerDist.includes('ambala') || lowerDist.includes('rohtak') || lowerDist.includes('sirsa')) {
          matchedKey = 'Haryana';
        } else if (lowerDist.includes('jodhpur') || lowerDist.includes('jaipur') || lowerDist.includes('bikaner') || lowerDist.includes('kota') || lowerDist.includes('sri ganganagar')) {
          matchedKey = 'Rajasthan';
        }
      }
    }

    if (matchedKey && INDIA_REGIONAL_SOIL_REGISTRY[matchedKey]) {
      const base = INDIA_REGIONAL_SOIL_REGISTRY[matchedKey];
      return {
        ...base,
        district: cleanDist || base.district || `${base.state} District`,
      };
    }

    // If no state or district matched, return authentic National Baseline rather than assuming Punjab
    return {
      ...INDIA_NATIONAL_SOIL_BASELINE,
      state: cleanState || 'India',
      district: cleanDist || 'Regional Centre',
    };
  }

  // International preset
  const intKeys = Object.keys(GLOBAL_REGIONAL_SOIL_PRESETS);
  const matchedIntKey = intKeys.find(
    (k) => k.toLowerCase() === (country || '').toLowerCase()
  ) || 'Brazil';

  return GLOBAL_REGIONAL_SOIL_PRESETS[matchedIntKey];
}

export interface SoilParameterValue<T = number | string> {
  value: T;
  unit?: string;
  rating: 'Low' | 'Medium' | 'Optimal' | 'High' | 'Very High' | 'Acidic' | 'Neutral' | 'Alkaline' | 'Saline' | 'Non-Saline';
  typicalRange: string;
  provenance: 'MEASURED' | 'REGIONAL_BASELINE' | 'SATELLITE_DERIVED' | 'ESTIMATED' | 'UNAVAILABLE';
  provenanceLabel: string;
  spatialResolution: string; // e.g. "Farm Level (Lab)", "District Baseline (Ludhiana)", "Zone Baseline (Zone VI)"
  confidence: 'High (Lab Verified)' | 'High (Survey Scale 1:50k)' | 'Moderate (Zonal Estimate)' | 'Satellite Telemetry';
  isLabMeasured: boolean;
}

export interface RegionalSoilProfile {
  state: string;
  district?: string;
  agroClimaticZone: string;
  primarySoilType: string;
  soilOrder: string; // e.g., "Inceptisol / Entisol", "Vertisol", "Alfisol"
  texture: string; // e.g., "Sandy Clay Loam", "Deep Heavy Clay", "Red Sandy Loam"
  drainageClass: 'Well Drained' | 'Moderately Well Drained' | 'Poorly Drained' | 'Excessively Drained';
  waterHoldingCapacity: 'Low' | 'Moderate' | 'High' | 'Very High';
  permeability: 'Slow' | 'Moderate' | 'Rapid';
  
  // Chemical & Physical Properties Baseline (ICAR / NRSC benchmarks)
  ph: SoilParameterValue<number>;
  nitrogen: SoilParameterValue<'Low' | 'Medium' | 'Optimal' | 'High'>;
  nitrogenKgHa?: SoilParameterValue<number>;
  phosphorus: SoilParameterValue<'Low' | 'Medium' | 'Optimal' | 'High'>;
  phosphorusKgHa?: SoilParameterValue<number>;
  potassium: SoilParameterValue<'Low' | 'Medium' | 'Optimal' | 'High'>;
  potassiumKgHa?: SoilParameterValue<number>;
  organicMatterPercent: SoilParameterValue<number>;
  electricalConductivityDsM: SoilParameterValue<number>; // Salinity index (dS/m)
  cationExchangeCapacity: SoilParameterValue<number>; // CEC meq/100g
  
  // Regional Constraints & Biological Guidance
  regionalDeficiencies: string[];
  microNutrientSensitivities: string[]; // e.g., "Zinc (Zn)", "Iron (Fe)", "Boron (B)"
  regenerativeFocus: string[];
  organicMatterTargetPercent: number;
  sourceAgency: string;
  datasetName: string;
}


export function localizeForecastDay(day: string, lang: Language): string {
  if (!day) return '';
  const norm = normalizeLang(lang);
  if (norm === 'en') return day;

  const dictionary = FORECAST_DAYS_MAP[norm];
  if (dictionary && dictionary[day]) {
    return dictionary[day];
  }

  return day;
}


export function localizeWeatherCondition(cond: string, lang: Language): string {
  if (!cond) return '';
  const norm = normalizeLang(lang);
  if (norm === 'en') return cond;

  const dictionary = WEATHER_CONDITIONS_MAP[norm];
  if (dictionary && dictionary[cond]) {
    return dictionary[cond];
  }

  // Substring search matching
  if (dictionary) {
    const lower = cond.toLowerCase();
    for (const [key, val] of Object.entries(dictionary)) {
      if (lower.includes(key.toLowerCase())) {
        return val;
      }
    }
  }

  return cond;
}


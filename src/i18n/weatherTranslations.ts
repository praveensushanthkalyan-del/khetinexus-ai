export function localizeWindSpeed(windStr: string, lang: Language): string {
  if (!windStr) return '';
  const norm = normalizeLang(lang);
  if (norm === 'en') return windStr;

  const dict = WIND_DIRECTIONS_MAP[norm];
  if (!dict) return windStr;

  let result = windStr;

  if (dict['km/h']) {
    result = result.replace(/km\/h/gi, dict['km/h']);
  }

  const directions = ['NNE', 'NNW', 'ENE', 'ESE', 'SSE', 'SSW', 'WNW', 'WSW', 'NE', 'NW', 'SE', 'SW', 'N', 'S', 'E', 'W'];
  for (const dir of directions) {
    if (dict[dir]) {
      const regex = new RegExp(`\\b${dir}\\b`, 'g');
      result = result.replace(regex, dict[dir]);
    }
  }

  return result;
}


export function localizeSoilOrder(order: string | undefined | null, lang: Language): string {
  if (!order) return '';
  const norm = (normalizeLang(lang) || 'en').toLowerCase();
  if (norm === 'en') return order;

  const lower = order.trim().toLowerCase();

  // Exact or contains match
  for (const [key, mapping] of Object.entries(SOIL_ORDER_MAP)) {
    if (lower === key || lower.includes(key) || key.includes(lower)) {
      if (mapping[norm]) return mapping[norm]!;
    }
  }

  // Broad taxonomy keyword match
  if (lower.includes('vertisol')) return SOIL_ORDER_MAP['vertisols'][norm] || order;
  if (lower.includes('inceptisol')) return SOIL_ORDER_MAP['inceptisols'][norm] || order;
  if (lower.includes('alfisol')) return SOIL_ORDER_MAP['alfisols'][norm] || order;
  if (lower.includes('ultisol')) return SOIL_ORDER_MAP['ultisols / inceptisols (lateritic acid soils)'][norm] || order;
  if (lower.includes('aridisol')) return SOIL_ORDER_MAP['aridisols (desert sandy soils)'][norm] || order;
  if (lower.includes('mollisol')) return SOIL_ORDER_MAP['mollisols / inceptisols (sub-montane soils)'][norm] || order;
  if (lower.includes('entisol')) return SOIL_ORDER_MAP['entisols (alluvial floodplains)'][norm] || order;
  if (lower.includes('oxisol') || lower.includes('latosol')) return SOIL_ORDER_MAP['oxisols (tropical highly weathered red soils)'][norm] || order;

  return order;
}


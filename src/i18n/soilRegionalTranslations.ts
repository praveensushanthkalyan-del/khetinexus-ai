export function localizeDatasetName(datasetName: string | undefined | null, lang: Language): string {
  if (!datasetName) return '';
  const norm = (normalizeLang(lang) || 'en').toLowerCase();
  if (norm === 'en') return datasetName;

  const lower = datasetName.trim().toLowerCase();
  for (const [key, mapping] of Object.entries(DATASET_NAME_MAP)) {
    if (lower === key || lower.includes(key) || key.includes(lower)) {
      if (mapping[norm]) return mapping[norm]!;
    }
  }

  return datasetName;
}


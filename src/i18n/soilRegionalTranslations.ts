export function localizeRegionalDeficiencyExtended(def: string, lang: Language): string {
  if (!def) return '';
  const norm = (normalizeLang(lang) || 'en').toLowerCase();
  if (norm === 'en') return def;

  const low = def.toLowerCase();
  for (const item of DEFICIENCY_EXTENDED_PATTERNS) {
    if (item.match(low)) {
      if (item.translations[norm]) {
        return item.translations[norm];
      }
    }
  }

  return def;
}


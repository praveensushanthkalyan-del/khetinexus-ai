export function localizePrimarySoilType(soilType: string | undefined | null, lang: Language): string {
  if (!soilType) return '';
  const norm = (normalizeLang(lang) || 'en').toLowerCase();
  if (norm === 'en') return soilType;

  const lower = soilType.trim().toLowerCase();
  for (const [key, mapping] of Object.entries(PRIMARY_SOIL_TYPE_MAP)) {
    if (lower === key || lower.includes(key) || key.includes(lower)) {
      if (mapping[norm]) return mapping[norm]!;
    }
  }

  return localizeSoilType(soilType, lang);
}
